-- =============================================================================
-- EuropeBus — intercity coach booking database
-- Dialect: PostgreSQL 14+ (kept close to portable SQL; Postgres-only parts are
--          marked "PG-ONLY" and are limited to triggers / plpgsql functions).
--
-- Conventions
--   * Every timestamp is TIMESTAMPTZ and stored/compared in UTC. Local times are
--     derived with  ts AT TIME ZONE city.timezone  (IANA zone names).
--   * Money is NUMERIC(10,2) in EUR; every money table carries a currency
--     column that is pinned to 'EUR' by a CHECK so a second currency later is a
--     constraint change, not a data migration.
--   * Status columns are TEXT + CHECK instead of enum types (portable, easy to
--     extend with ALTER TABLE ... DROP/ADD CONSTRAINT).
--   * Surrogate keys are identity columns; natural keys get UNIQUE constraints.
--
-- Run on an empty database:  psql -v ON_ERROR_STOP=1 -d europebus -f schema.sql
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- Geography: countries, cities, stops
-- -----------------------------------------------------------------------------
CREATE TABLE country (
    country_code  CHAR(2)      PRIMARY KEY,               -- ISO 3166-1 alpha-2
    name          VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT country_code_upper CHECK (country_code = UPPER(country_code))
);

CREATE TABLE city (
    city_id       INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    country_code  CHAR(2)      NOT NULL REFERENCES country (country_code),
    timezone      VARCHAR(64)  NOT NULL,                  -- IANA, e.g. 'Europe/Paris'
    CONSTRAINT city_name_country_uq UNIQUE (name, country_code)
);

CREATE TABLE stop (
    stop_id       INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id       INTEGER      NOT NULL REFERENCES city (city_id),
    code          VARCHAR(10)  NOT NULL UNIQUE,           -- short code, e.g. 'PAR-BER'
    name          VARCHAR(150) NOT NULL,
    address       VARCHAR(255),
    latitude      NUMERIC(9,6) CHECK (latitude  BETWEEN -90  AND 90),
    longitude     NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180),
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX stop_city_idx ON stop (city_id);

-- -----------------------------------------------------------------------------
-- Operators, drivers, fleet
-- -----------------------------------------------------------------------------
CREATE TABLE operator (
    operator_id   INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,
    legal_name    VARCHAR(200) NOT NULL,
    vat_number    VARCHAR(20)  UNIQUE,
    country_code  CHAR(2)      NOT NULL REFERENCES country (country_code),
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE driver (
    driver_id         INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id       INTEGER      NOT NULL REFERENCES operator (operator_id),
    first_name        VARCHAR(80)  NOT NULL,
    last_name         VARCHAR(80)  NOT NULL,
    license_number    VARCHAR(30)  NOT NULL,
    license_country   CHAR(2)      NOT NULL REFERENCES country (country_code),
    license_expiry    DATE         NOT NULL,
    is_active         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT driver_license_uq UNIQUE (license_country, license_number)
);
CREATE INDEX driver_operator_idx ON driver (operator_id);

-- A seat layout is a coach model's floor plan; many buses share one layout.
CREATE TABLE seat_layout (
    layout_id     INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,           -- e.g. 'Setra S 516 HD 2+2'
    decks         SMALLINT     NOT NULL DEFAULT 1 CHECK (decks IN (1, 2)),
    description   VARCHAR(255)
);

CREATE TABLE seat (
    seat_id       INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layout_id     INTEGER      NOT NULL REFERENCES seat_layout (layout_id) ON DELETE CASCADE,
    seat_label    VARCHAR(5)   NOT NULL,                  -- what the passenger sees: '12C'
    deck          SMALLINT     NOT NULL DEFAULT 1 CHECK (deck IN (1, 2)),
    row_no        SMALLINT     NOT NULL CHECK (row_no > 0),
    column_letter CHAR(1)      NOT NULL,
    seat_type     VARCHAR(12)  NOT NULL DEFAULT 'standard'
                  CHECK (seat_type IN ('standard', 'premium', 'wheelchair')),
    is_window     BOOLEAN      NOT NULL DEFAULT FALSE,
    surcharge_eur NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (surcharge_eur >= 0),
    CONSTRAINT seat_label_uq     UNIQUE (layout_id, seat_label),
    CONSTRAINT seat_position_uq  UNIQUE (layout_id, deck, row_no, column_letter),
    CONSTRAINT seat_layout_id_uq UNIQUE (layout_id, seat_id)      -- target for composite FKs
);

CREATE TABLE bus (
    bus_id             INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id        INTEGER      NOT NULL REFERENCES operator (operator_id),
    layout_id          INTEGER      NOT NULL REFERENCES seat_layout (layout_id),
    registration_plate VARCHAR(15)  NOT NULL,
    registration_country CHAR(2)    NOT NULL REFERENCES country (country_code),
    manufacturer       VARCHAR(50),
    model              VARCHAR(50),
    year_built         SMALLINT     CHECK (year_built BETWEEN 1990 AND 2100),
    has_wifi           BOOLEAN      NOT NULL DEFAULT TRUE,
    has_toilet         BOOLEAN      NOT NULL DEFAULT TRUE,
    is_active          BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT bus_plate_uq     UNIQUE (registration_country, registration_plate),
    CONSTRAINT bus_layout_id_uq UNIQUE (bus_id, layout_id)            -- target for trip FK
);
CREATE INDEX bus_operator_idx ON bus (operator_id);

-- Capacity is derived from the layout so it can never drift from the seat list.
CREATE VIEW v_bus_capacity AS
SELECT b.bus_id, b.registration_plate, l.name AS layout_name,
       COUNT(s.seat_id) AS seat_capacity,
       COUNT(s.seat_id) FILTER (WHERE s.seat_type = 'wheelchair') AS wheelchair_spaces
FROM bus b
JOIN seat_layout l ON l.layout_id = b.layout_id
LEFT JOIN seat s   ON s.layout_id = l.layout_id
GROUP BY b.bus_id, b.registration_plate, l.name;

-- -----------------------------------------------------------------------------
-- Network: routes and ordered route stops
-- -----------------------------------------------------------------------------
CREATE TABLE route (
    route_id      INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(10)  NOT NULL UNIQUE,           -- e.g. 'EB101'
    name          VARCHAR(150) NOT NULL,
    operator_id   INTEGER      NOT NULL REFERENCES operator (operator_id),
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE
);

-- stop_seq orders the stops (1 = origin). Offsets are minutes after the
-- origin departure and are the template used to generate trip_stop rows.
CREATE TABLE route_stop (
    route_id              INTEGER  NOT NULL REFERENCES route (route_id) ON DELETE CASCADE,
    stop_seq              SMALLINT NOT NULL CHECK (stop_seq > 0),
    stop_id               INTEGER  NOT NULL REFERENCES stop (stop_id),
    arrival_offset_min    INTEGER  NOT NULL CHECK (arrival_offset_min >= 0),
    departure_offset_min  INTEGER  NOT NULL,
    distance_km           NUMERIC(7,1) NOT NULL CHECK (distance_km >= 0),  -- from origin
    PRIMARY KEY (route_id, stop_seq),
    CONSTRAINT route_stop_once_uq UNIQUE (route_id, stop_id),
    CONSTRAINT route_stop_dwell_ck CHECK (departure_offset_min >= arrival_offset_min)
);
CREATE INDEX route_stop_stop_idx ON route_stop (stop_id);

-- -----------------------------------------------------------------------------
-- Pricing (EUR)
-- -----------------------------------------------------------------------------
-- Base price for travelling from one stop to a later stop of the same route.
CREATE TABLE fare (
    fare_id       INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id      INTEGER      NOT NULL,
    from_seq      SMALLINT     NOT NULL,
    to_seq        SMALLINT     NOT NULL,
    fare_class    VARCHAR(10)  NOT NULL DEFAULT 'standard'
                  CHECK (fare_class IN ('saver', 'standard', 'flex')),
    price_eur     NUMERIC(10,2) NOT NULL CHECK (price_eur >= 0),
    currency      CHAR(3)      NOT NULL DEFAULT 'EUR' CHECK (currency = 'EUR'),
    valid_from    DATE         NOT NULL,
    valid_to      DATE,                                    -- NULL = open-ended
    FOREIGN KEY (route_id, from_seq) REFERENCES route_stop (route_id, stop_seq),
    FOREIGN KEY (route_id, to_seq)   REFERENCES route_stop (route_id, stop_seq),
    CONSTRAINT fare_direction_ck CHECK (to_seq > from_seq),
    CONSTRAINT fare_validity_ck  CHECK (valid_to IS NULL OR valid_to >= valid_from),
    CONSTRAINT fare_uq UNIQUE (route_id, from_seq, to_seq, fare_class, valid_from)
);

-- Percentage discount by passenger type, applied to the fare.
CREATE TABLE passenger_discount (
    passenger_type VARCHAR(10)  PRIMARY KEY
                   CHECK (passenger_type IN ('adult', 'child', 'youth', 'senior')),
    discount_pct   NUMERIC(5,2) NOT NULL CHECK (discount_pct BETWEEN 0 AND 100),
    description    VARCHAR(100)
);

-- -----------------------------------------------------------------------------
-- Operations: scheduled trips, per-stop UTC times, driver assignments
-- -----------------------------------------------------------------------------
CREATE TABLE trip (
    trip_id        INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_code      VARCHAR(30) NOT NULL UNIQUE,            -- 'EB101-20261204-0800'
    route_id       INTEGER     NOT NULL REFERENCES route (route_id),
    bus_id         INTEGER     NOT NULL,
    layout_id      INTEGER     NOT NULL,                   -- copied from bus, enforced by FK
    service_date   DATE        NOT NULL,                   -- local date at the origin
    departure_utc  TIMESTAMPTZ NOT NULL,
    arrival_utc    TIMESTAMPTZ NOT NULL,
    status         VARCHAR(12) NOT NULL DEFAULT 'scheduled'
                   CHECK (status IN ('scheduled', 'boarding', 'departed', 'arrived', 'cancelled')),
    FOREIGN KEY (bus_id, layout_id) REFERENCES bus (bus_id, layout_id),
    CONSTRAINT trip_times_ck      CHECK (arrival_utc > departure_utc),
    CONSTRAINT trip_route_dep_uq  UNIQUE (route_id, departure_utc),
    CONSTRAINT trip_route_id_uq   UNIQUE (trip_id, route_id),    -- targets for composite FKs
    CONSTRAINT trip_layout_id_uq  UNIQUE (trip_id, layout_id)
);
CREATE INDEX trip_departure_idx  ON trip (departure_utc);
CREATE INDEX trip_route_date_idx ON trip (route_id, service_date);
CREATE INDEX trip_bus_idx        ON trip (bus_id, departure_utc);

-- Concrete UTC times of one trip at each of its route's stops.
CREATE TABLE trip_stop (
    trip_id        INTEGER     NOT NULL,
    route_id       INTEGER     NOT NULL,
    stop_seq       SMALLINT    NOT NULL,
    arrival_utc    TIMESTAMPTZ NOT NULL,
    departure_utc  TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (trip_id, stop_seq),
    FOREIGN KEY (trip_id, route_id)  REFERENCES trip (trip_id, route_id) ON DELETE CASCADE,
    FOREIGN KEY (route_id, stop_seq) REFERENCES route_stop (route_id, stop_seq),
    CONSTRAINT trip_stop_dwell_ck CHECK (departure_utc >= arrival_utc)
);
CREATE INDEX trip_stop_route_seq_idx ON trip_stop (route_id, stop_seq, departure_utc);

CREATE TABLE trip_driver (
    trip_id    INTEGER     NOT NULL REFERENCES trip (trip_id) ON DELETE CASCADE,
    driver_id  INTEGER     NOT NULL REFERENCES driver (driver_id),
    role       VARCHAR(10) NOT NULL DEFAULT 'primary' CHECK (role IN ('primary', 'relief')),
    PRIMARY KEY (trip_id, driver_id)
);
CREATE INDEX trip_driver_driver_idx ON trip_driver (driver_id);
-- At most one primary driver per trip.
CREATE UNIQUE INDEX trip_driver_one_primary_uq ON trip_driver (trip_id) WHERE role = 'primary';

-- -----------------------------------------------------------------------------
-- Customers and bookings
-- -----------------------------------------------------------------------------
CREATE TABLE customer (
    customer_id   INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL,
    first_name    VARCHAR(80)  NOT NULL,
    last_name     VARCHAR(80)  NOT NULL,
    phone         VARCHAR(20),                             -- E.164, e.g. '+33612345678'
    country_code  CHAR(2)      REFERENCES country (country_code),
    marketing_opt_in BOOLEAN   NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Case-insensitive unique e-mail.
CREATE UNIQUE INDEX customer_email_uq ON customer (LOWER(email));

-- One booking = one customer, one trip, one boarding->alighting segment,
-- one or more passengers/seats.
CREATE TABLE booking (
    booking_id      INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_ref     CHAR(8)      NOT NULL UNIQUE,          -- shown to the customer
    customer_id     INTEGER      NOT NULL REFERENCES customer (customer_id),
    trip_id         INTEGER      NOT NULL REFERENCES trip (trip_id),
    from_seq        SMALLINT     NOT NULL,                 -- boarding stop
    to_seq          SMALLINT     NOT NULL,                 -- alighting stop
    fare_class      VARCHAR(10)  NOT NULL DEFAULT 'standard'
                    CHECK (fare_class IN ('saver', 'standard', 'flex')),
    status          VARCHAR(10)  NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'confirmed', 'cancelled', 'expired', 'completed')),
    total_eur       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (total_eur >= 0),
    currency        CHAR(3)      NOT NULL DEFAULT 'EUR' CHECK (currency = 'EUR'),
    sales_channel   VARCHAR(10)  NOT NULL DEFAULT 'web'
                    CHECK (sales_channel IN ('web', 'app', 'agent', 'counter')),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (trip_id, from_seq) REFERENCES trip_stop (trip_id, stop_seq),
    FOREIGN KEY (trip_id, to_seq)   REFERENCES trip_stop (trip_id, stop_seq),
    CONSTRAINT booking_direction_ck CHECK (to_seq > from_seq),
    CONSTRAINT booking_trip_uq UNIQUE (booking_id, trip_id)          -- target for composite FK
);
CREATE INDEX booking_customer_idx ON booking (customer_id, created_at);
CREATE INDEX booking_trip_idx     ON booking (trip_id);
CREATE INDEX booking_status_idx   ON booking (status);

-- One row per passenger on a booking, with the seat they hold. The composite
-- FKs guarantee the seat belongs to the layout of the bus running this trip.
CREATE TABLE booking_seat (
    booking_seat_id INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      INTEGER      NOT NULL,
    trip_id         INTEGER      NOT NULL,
    layout_id       INTEGER      NOT NULL,
    seat_id         INTEGER      NOT NULL,
    passenger_first_name VARCHAR(80) NOT NULL,
    passenger_last_name  VARCHAR(80) NOT NULL,
    passenger_type  VARCHAR(10)  NOT NULL DEFAULT 'adult' REFERENCES passenger_discount (passenger_type),
    price_eur       NUMERIC(10,2) NOT NULL CHECK (price_eur >= 0),   -- price snapshot at sale
    FOREIGN KEY (booking_id, trip_id) REFERENCES booking (booking_id, trip_id) ON DELETE CASCADE,
    FOREIGN KEY (trip_id, layout_id)  REFERENCES trip (trip_id, layout_id),
    FOREIGN KEY (layout_id, seat_id)  REFERENCES seat (layout_id, seat_id),
    CONSTRAINT booking_seat_once_uq   UNIQUE (booking_id, seat_id),
    CONSTRAINT booking_seat_target_uq UNIQUE (booking_seat_id, trip_id, seat_id)
);
CREATE INDEX booking_seat_trip_seat_idx ON booking_seat (trip_id, seat_id);

-- Seat occupancy per LEG. A leg is identified by the stop_seq it starts at:
-- leg N runs from stop N to stop N+1. A passenger travelling stop 1 -> stop 3
-- holds legs 1 and 2. The primary key makes it impossible for two active
-- bookings to hold the same seat on the same leg, i.e. overlapping segments
-- are rejected by the database, while non-overlapping ones (Paris->Brussels
-- and Brussels->Amsterdam on seat 3A) can share the seat.
-- Rows are deleted when a booking is cancelled/expired (history lives in
-- booking_seat + booking_status_history).
CREATE TABLE seat_reservation (
    trip_id          INTEGER  NOT NULL,
    seat_id          INTEGER  NOT NULL,
    leg_seq          SMALLINT NOT NULL,
    booking_seat_id  INTEGER  NOT NULL,
    PRIMARY KEY (trip_id, seat_id, leg_seq),
    FOREIGN KEY (booking_seat_id, trip_id, seat_id)
        REFERENCES booking_seat (booking_seat_id, trip_id, seat_id) ON DELETE CASCADE,
    FOREIGN KEY (trip_id, leg_seq) REFERENCES trip_stop (trip_id, stop_seq)
);
CREATE INDEX seat_reservation_booking_seat_idx ON seat_reservation (booking_seat_id);

-- -----------------------------------------------------------------------------
-- Payments, cancellations, refunds  (no card data is ever stored)
-- -----------------------------------------------------------------------------
CREATE TABLE payment (
    payment_id         INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id         INTEGER      NOT NULL REFERENCES booking (booking_id),
    amount_eur         NUMERIC(10,2) NOT NULL CHECK (amount_eur > 0),
    currency           CHAR(3)      NOT NULL DEFAULT 'EUR' CHECK (currency = 'EUR'),
    method             VARCHAR(12)  NOT NULL
                       CHECK (method IN ('card', 'paypal', 'sepa', 'ideal', 'apple_pay', 'google_pay', 'voucher')),
    provider           VARCHAR(30)  NOT NULL,              -- PSP name, e.g. 'adyen'
    provider_reference VARCHAR(64),                        -- PSP transaction id (opaque token)
    status             VARCHAR(20)  NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending', 'authorized', 'captured', 'failed',
                                         'refunded', 'partially_refunded')),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT payment_provider_ref_uq UNIQUE (provider, provider_reference)
);
CREATE INDEX payment_booking_idx ON payment (booking_id);
CREATE INDEX payment_status_idx  ON payment (status, created_at);

CREATE TABLE cancellation (
    cancellation_id  INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id       INTEGER      NOT NULL UNIQUE REFERENCES booking (booking_id),
    cancelled_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    initiated_by     VARCHAR(10)  NOT NULL CHECK (initiated_by IN ('customer', 'operator', 'system')),
    reason           VARCHAR(255),
    refund_pct       NUMERIC(5,2) NOT NULL CHECK (refund_pct BETWEEN 0 AND 100),
    refund_due_eur   NUMERIC(10,2) NOT NULL CHECK (refund_due_eur >= 0)
);

CREATE TABLE refund (
    refund_id          INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id         INTEGER      NOT NULL REFERENCES payment (payment_id),
    cancellation_id    INTEGER      REFERENCES cancellation (cancellation_id),
    amount_eur         NUMERIC(10,2) NOT NULL CHECK (amount_eur > 0),
    currency           CHAR(3)      NOT NULL DEFAULT 'EUR' CHECK (currency = 'EUR'),
    status             VARCHAR(10)  NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending', 'processed', 'failed')),
    provider_reference VARCHAR(64),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at       TIMESTAMPTZ,
    CONSTRAINT refund_processed_ck CHECK (status <> 'processed' OR processed_at IS NOT NULL)
);
CREATE INDEX refund_payment_idx      ON refund (payment_id);
CREATE INDEX refund_cancellation_idx ON refund (cancellation_id);

-- -----------------------------------------------------------------------------
-- Audit: append-only booking status history
-- -----------------------------------------------------------------------------
CREATE TABLE booking_status_history (
    history_id   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id   INTEGER      NOT NULL REFERENCES booking (booking_id),
    old_status   VARCHAR(10),                              -- NULL for the creation event
    new_status   VARCHAR(10)  NOT NULL,
    changed_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by   VARCHAR(64)  NOT NULL DEFAULT 'system',   -- app user / service name
    note         VARCHAR(255)
);
CREATE INDEX booking_status_history_booking_idx ON booking_status_history (booking_id, changed_at);

-- =============================================================================
-- PG-ONLY: triggers. Each one is optional for portability; the README lists
-- what the application must do instead on other databases.
-- =============================================================================

-- 1) Write a history row whenever a booking is created or changes status.
--    The actor comes from   SET LOCAL europebus.actor = '<who>';   (default 'system')
--    and an optional note from   SET LOCAL europebus.note = '<why>';
CREATE FUNCTION trg_booking_status_history() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' OR NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO booking_status_history (booking_id, old_status, new_status, changed_by, note)
        VALUES (NEW.booking_id,
                CASE WHEN TG_OP = 'UPDATE' THEN OLD.status END,
                NEW.status,
                COALESCE(NULLIF(current_setting('europebus.actor', true), ''), 'system'),
                NULLIF(current_setting('europebus.note', true), ''));
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER booking_status_history_aiu
AFTER INSERT OR UPDATE OF status ON booking
FOR EACH ROW EXECUTE FUNCTION trg_booking_status_history();

-- 2) The history table is append-only.
CREATE FUNCTION trg_forbid_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only (% not allowed)', TG_TABLE_NAME, TG_OP;
END $$;

CREATE TRIGGER booking_status_history_append_only
BEFORE UPDATE OR DELETE ON booking_status_history
FOR EACH ROW EXECUTE FUNCTION trg_forbid_change();

-- 3) A seat_reservation leg must lie inside its booking's segment
--    (from_seq <= leg_seq < to_seq) and the booking must be active.
CREATE FUNCTION trg_seat_reservation_check() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    b booking%ROWTYPE;
BEGIN
    SELECT bk.* INTO b
    FROM booking_seat bs JOIN booking bk ON bk.booking_id = bs.booking_id
    WHERE bs.booking_seat_id = NEW.booking_seat_id;

    IF NEW.leg_seq < b.from_seq OR NEW.leg_seq >= b.to_seq THEN
        RAISE EXCEPTION 'leg % is outside booking % segment [%..%)',
              NEW.leg_seq, b.booking_ref, b.from_seq, b.to_seq;
    END IF;
    IF b.status NOT IN ('pending', 'confirmed') THEN
        RAISE EXCEPTION 'booking % is %, it cannot hold seats', b.booking_ref, b.status;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER seat_reservation_check
BEFORE INSERT OR UPDATE ON seat_reservation
FOR EACH ROW EXECUTE FUNCTION trg_seat_reservation_check();

-- 4) Release seats automatically when a booking is cancelled or expires.
CREATE FUNCTION trg_booking_release_seats() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM seat_reservation sr
    USING booking_seat bs
    WHERE bs.booking_seat_id = sr.booking_seat_id
      AND bs.booking_id = NEW.booking_id;
    RETURN NEW;
END $$;

CREATE TRIGGER booking_release_seats
AFTER UPDATE OF status ON booking
FOR EACH ROW
WHEN (NEW.status IN ('cancelled', 'expired') AND OLD.status IN ('pending', 'confirmed'))
EXECUTE FUNCTION trg_booking_release_seats();

COMMIT;
